#!/usr/bin/env python3
"""Generate tb_false_flag_envelope.spice: the W1-W5 false-flag waveform set (spec row 8)
on the BEHAVIOURAL-ENVELOPE rail (spec "Rail model", form 2: an ASSUMPTION, not a
measurement), seen by four detector copies (one per select code).

Rail shapes follow sim/tb_rail_model_check/gen_envelope.py (same window, same W2 tones,
same W3 pseudo-noise, same W4 / W5 edges); that bench checks the envelope against its
bounds, this one applies it to the detector. W5 is applied twice: with the 1 ns edges of
the envelope and as an ideal step (1 ps edges), the additional case.

usage: gen_envelope_ff.py OUT.spice [NEGCTL_MV]
  NEGCTL_MV  push the W4 excursion NEGCTL_MV below the 1.764 V window edge, so the detector
             must flag: the negative control that proves the bench can see a flag.
Placeholders __PDK_LIB__ __PROC__ __TEMP__ __VSUP__ __NETLIST__ are left for run.sh.
"""
import math
import sys

NOM = 1.8
WIN_LO, WIN_HI = 1.764, 1.836
BAND = 0.018
GAP = 200e-9


def fmt(x):
    return f"{x:.12g}"


def main(out, negctl_mv):
    pts = [(0.0, NOM)]
    tones = []
    cases = []          # (name, t0, t1)
    t = 0.0

    def to(tt, v):
        nonlocal t
        pts.append((tt, v))
        t = tt

    def ramp(d, v):
        to(t + d, v)

    def hold(d):
        to(t + d, pts[-1][1])

    ramp(12e-6, NOM)     # start-up: CLR pulse (1-5 us) and the flag settle before any case
    # W1
    for tag, v in (("lo", WIN_LO), ("nom", NOM), ("hi", WIN_HI)):
        ramp(1e-6, v)
        t0 = t
        hold(2e-6)
        cases.append((f"w1_{tag}", t0, t))
    ramp(1e-6, NOM)
    hold(GAP)
    # W2
    for tag, f, cyc in (("1k", 1e3, 1), ("100k", 1e5, 5), ("10m", 1e7, 20)):
        t0 = t
        dur = cyc / f
        hold(dur)
        tones.append(f"(u(time-{fmt(t0)})-u(time-{fmt(t0 + dur)}))*{BAND}*sin(2*pi*{fmt(f)}*(time-{fmt(t0)}))")
        cases.append((f"w2_{tag}", t0, t0 + dur))
        hold(GAP)
    # W3
    t0 = t
    dur = 20e-6
    hold(dur)
    terms = []
    for k in range(16):
        fk = 2e5 * (100e6 / 2e5) ** (k / 15) * (1 + 0.013 * k)
        ph = (k * 2.399963) % (2 * math.pi)
        terms.append(f"0.0015*sin(2*pi*{fmt(fk)}*(time-{fmt(t0)})+{fmt(ph)})")
    taper = f"sin(pi*(time-{fmt(t0)})/{fmt(dur)})"
    tones.append(f"(u(time-{fmt(t0)})-u(time-{fmt(t0 + dur)}))*{taper}*({'+'.join(terms)})")
    cases.append(("w3", t0, t0 + dur))
    hold(GAP)
    # W4 (negative control pushes the excursion below the window)
    t0 = t
    low = WIN_LO - negctl_mv * 1e-3
    ramp(1e-6, low)
    hold(5e-6)
    ramp(1e-6, NOM)
    hold(2e-6)
    cases.append(("w4", t0, t))
    hold(GAP)
    # W5: 1 ns edges (envelope) then 1 ps edges (ideal step); down and up
    for kind, edge in (("env", 1e-9), ("ideal", 1e-12)):
        for tag, v in (("dn", WIN_LO), ("up", WIN_HI)):
            t0 = t
            ramp(edge, v)
            hold(5e-9 - edge)               # FWHM ~ 5 ns
            ramp(edge, NOM)
            hold(30e-9)
            cases.append((f"w5_{kind}_{tag}", t0 - 5e-9, t))
            hold(GAP)
    tstop = t + 1e-6
    pwl = " ".join(f"{fmt(a)} {fmt(b)}" for a, b in pts)
    s = [
        "* tb_false_flag, BEHAVIOURAL-ENVELOPE rail (ASSUMPTION, not a measurement; spec \"Rail model\" form 2).",
        "* Generated by gen_envelope_ff.py; do not edit. W1 static, W2 +-1 % tones, W3 bounded",
        "* pseudo-noise, W4 slow excursion to the window edge, W5 spike (1 ns edges, and ideal step).",
        f"* NEGCTL_MV={negctl_mv}",
        '.lib "__PDK_LIB__" __PROC__',
        '.include "__NETLIST__"',
        ".temp __TEMP__",
        ".param vsup=__VSUP__",
        ".option method=gear",
        f"Vbase base 0 PWL({pwl})",
        f"Btone tone 0 V='{'+'.join(tones)}'",
        "Erail rail 0 vol='v(base)+v(tone)'",
        "Rload rail 0 1k",
        "Vlo lo 0 0",
        "Vhi hi 0 {vsup}",
        "Vclr clr 0 PWL(0 0 1u 0 1.1u {vsup} 5u {vsup} 5.1u 0)",
    ]
    codes = [("lo", "lo"), ("hi", "lo"), ("lo", "hi"), ("hi", "hi")]
    for i, (a, b) in enumerate(codes):
        s.append(f"Vd{i} vd{i} 0 {{vsup}}")
        s.append(f"X{i} rail {a} {b} clr vd{i} 0 l{i} st{i} detector_top")
    s += [".control", "set num_threads=1", f"tran 5n {fmt(tstop)} 0 20n"]
    s.append(f'meas tran start_live_max max v(l0) from=7u to=11u')
    for name, a, b in cases:
        s.append(f"meas tran {name}_vmin min v(rail) from={fmt(a)} to={fmt(b)}")
        s.append(f'echo "RESULT {name}_vmin = $&{name}_vmin"')
        s.append(f"meas tran {name}_vmax max v(rail) from={fmt(a)} to={fmt(b)}")
        s.append(f'echo "RESULT {name}_vmax = $&{name}_vmax"')
        for i in range(4):
            s.append(f"meas tran {name}_live_l{i} max v(l{i}) from={fmt(a)} to={fmt(b)}")
            s.append(f'echo "RESULT {name}_live_l{i} = $&{name}_live_l{i}"')
    for i in range(4):
        s.append(f"meas tran sticky_l{i} max v(st{i}) from=7u to={fmt(tstop)}")
        s.append(f'echo "RESULT sticky_l{i} = $&sticky_l{i}"')
    s += ["quit", ".endc", ".end"]
    open(out, "w").write("\n".join(s) + "\n")
    print(" ".join(n for n, _, _ in cases))


if __name__ == "__main__":
    main(sys.argv[1], float(sys.argv[2]) if len(sys.argv) > 2 else 0.0)
